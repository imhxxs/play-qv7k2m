/** 댓글 수(삭제·가려진 것 포함, 깜짝 연출 자리는 나타난 뒤에만) */
export function commentCount(post, { ghostShown = false, extra = 0 } = {}) {
  return (post.comments?.length || 0) + (post.ghost && ghostShown ? 1 : 0) + extra;
}
