/** 글자 → { hun, eum } */
export const HANJA = new Map();

for (const item of RAW.split(/[|\n]/)) {
  const t = item.trim();
  if (!t) continue;
  const ch = [...t][0];
  const rest = t.slice(ch.length).trim().split(/\s+/);
  const eum = rest.pop();
  const hun = rest.join(' ');
  if (!eum || HANJA.has(ch)) continue;
  HANJA.set(ch.normalize('NFC'), { hun, eum });
}

/** 한자 한 글자의 음훈. 없으면 null */
export function hanjaInfo(ch) {
  return HANJA.get(String(ch).normalize('NFC')) || null;
}

/** 이 글자가 한자(CJK 통합 한자·호환 한자)인가 */
export function isHanja(ch) {
  const c = String(ch).codePointAt(0);
  return (c >= 0x4e00 && c <= 0x9fff) || (c >= 0x3400 && c <= 0x4dbf) || (c >= 0xf900 && c <= 0xfaff) || (c >= 0x20000 && c <= 0x2fa1f);
}

/** 음이 같은 한자들(사전 '한자 찾기'). 두음법칙으로 바뀐 음(예: '연' → 蓮 련)도 함께 찾는다. */
export function hanjaByEum(syllable, initialVariants = []) {
  const keys = new Set([syllable, ...initialVariants]);
  const out = [];
  for (const [ch, v] of HANJA) if (keys.has(v.eum)) out.push({ ch, ...v });
  return out;
}
