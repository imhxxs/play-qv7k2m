/** 장(章)에 맞게 보이는 공지(최신순, 고정 글 먼저) */
export function visibleNotices(chapter) {
  const list = NOTICES.filter((n) => !n.minChapter || chapter >= n.minChapter);
  const byDate = (a, b) => (b.date + b.time).localeCompare(a.date + a.time);
  return [...list.filter((n) => n.pin).sort(byDate), ...list.filter((n) => !n.pin).sort(byDate)];
}

/** 날짜순(고정 무시) 이웃 글 */
export function neighbors(chapter, id) {
  const list = NOTICES.filter((n) => !n.minChapter || chapter >= n.minChapter)
    .sort((a, b) => (b.date + b.time).localeCompare(a.date + a.time));
  const i = list.findIndex((n) => n.id === id);
  return { newer: i > 0 ? list[i - 1] : null, older: i >= 0 && i < list.length - 1 ? list[i + 1] : null };
}

