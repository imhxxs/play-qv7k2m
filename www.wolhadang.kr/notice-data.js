export const byId = (id) => NOTICES.find((n) => String(n.id) === String(id)) || null;

/** 게시판 순서: 고정 글 먼저, 그다음 번호 큰 순 */
export function boardOrder() {
  const pins = NOTICES.filter((n) => n.pin).sort((a, b) => b.no - a.no);
  const rest = [...NOTICES].sort((a, b) => b.no - a.no);
  return { pins, rest };
}
